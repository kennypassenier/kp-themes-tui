// The twenty-two kp-themes palettes as Rust, for the kp-tui-palette crate
// [kp-themes scope-127, scope-128, scope-139].
//
// A generated palette with no judgement in it; the anatomy and the widgets
// in the kp-tui crate are hand-written. The tokens come from
// vendor/kp-themes/, the kp-themes release vendor/PIN names, and the output
// is committed, so a binary built from this workspace needs no node and no
// network: node runs only here, when the pin moves, and in the gates, where
// `--check` refuses a palette that drifted from the tokens.
//
// Usage:
//   node gates/generate-tui-palette.mjs           write crates/kp-tui-palette/src/generated_palette.rs
//   node gates/generate-tui-palette.mjs --check   exit 1 if it would change

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { themes } from '../vendor/kp-themes/gates/check-invariants.mjs';
import { derivedBlock, rgbOf } from '../vendor/kp-themes/gates/palette.mjs';

const OUT = new URL('../crates/kp-tui-palette/src/', import.meta.url);
/** The kp-themes release vendor/PIN names; the palette carries it as KP_THEMES_VERSION. */
const VERSION = readFileSync(new URL('../vendor/kp-themes/VERSION', import.meta.url), 'utf8').trim();

/**
 * Rust field, CSS token, and the role a sixteen-colour terminal falls back
 * through. The list is the demo's, which was read off the widgets: every
 * colour a component actually paints, and nothing a theme merely declares.
 */
const FIELDS = [
    ['background', 'background', 'Surface'],
    ['foreground', 'foreground', 'Ink'],
    ['card', 'card', 'Surface'],
    ['card_foreground', 'card-foreground', 'Ink'],
    ['popover', 'popover', 'Surface'],
    ['popover_foreground', 'popover-foreground', 'Ink'],
    ['primary', 'primary', 'Fill'],
    ['primary_foreground', 'primary-foreground', 'OnFill'],
    ['primary_hover', 'primary-hover', 'Fill'],
    ['primary_active', 'primary-active', 'Fill'],
    ['primary_disabled', 'primary-disabled', 'Fill'],
    ['secondary', 'secondary', 'Surface'],
    ['secondary_foreground', 'secondary-foreground', 'Ink'],
    ['secondary_active', 'secondary-active', 'Surface'],
    ['muted', 'muted', 'Surface'],
    ['muted_foreground', 'muted-foreground', 'MutedInk'],
    ['accent', 'accent', 'Fill'],
    ['accent_foreground', 'accent-foreground', 'OnFill'],
    ['destructive', 'destructive', 'Fill'],
    ['destructive_foreground', 'destructive-foreground', 'OnFill'],
    ['success', 'success', 'Fill'],
    ['success_foreground', 'success-foreground', 'OnFill'],
    ['warning', 'warning', 'Fill'],
    ['warning_foreground', 'warning-foreground', 'OnFill'],
    ['info', 'info', 'Fill'],
    ['info_foreground', 'info-foreground', 'OnFill'],
    ['border', 'border', 'Line'],
    ['border_strong', 'border-strong', 'Line'],
    ['ring', 'ring', 'Line'],
    ['chart_1', 'chart-1', 'Fill'],
    ['chart_2', 'chart-2', 'Fill'],
    ['chart_3', 'chart-3', 'Fill'],
    ['chart_4', 'chart-4', 'Fill'],
    ['chart_5', 'chart-5', 'Fill'],
    ['code_keyword', 'code-keyword', 'Ink'],
    ['code_string', 'code-string', 'Ink'],
];

/** @returns {string} */
export function render() {
    const all = themes();
    let out = '';
    out += `// GENERATED by kp-themes ${VERSION} (gates/generate-tui-palette.mjs). Do not edit.\n`;
    out += '//\n';
    out += "// Every theme's colours, as the terminal receives them. The anatomy —\n";
    out += '// border glyphs, case, prefixes, the cursor, the reveal — is judgement\n';
    out += '// and lives in kp-tui, hand-written. This file is data.\n\n';
    out += `pub const KP_THEMES_VERSION: &str = ${JSON.stringify(VERSION)};\n\n`;
    out += '/// A colour as three bytes; a terminal at a lower depth maps it itself.\n';
    out += '#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct Rgb(pub u8, pub u8, pub u8);\n\n';
    out += '/// What a colour is FOR, which is what a sixteen-colour terminal needs\n';
    out += '/// in order to fall back without losing the difference between a plate\n';
    out += '/// and the ink on it.\n';
    out += '#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Role {\n';
    for (const role of [...new Set(FIELDS.map((f) => f[2]))]) out += `    ${role},\n`;
    out += '}\n\n';
    out += '#[derive(Clone, Copy, Debug, PartialEq)]\npub struct Palette<C> {\n';
    for (const [field, token] of FIELDS) out += `    /// \`--${token}\`\n    pub ${field}: C,\n`;
    out += '}\n\nimpl<C: Copy> Palette<C> {\n';
    out += '    /// The same shape in another colour type: resolve each field for\n    /// the terminal at hand.\n';
    out += '    pub fn map<D>(&self, f: impl Fn(Role, C) -> D) -> Palette<D> {\n        Palette {\n';
    for (const [field, , role] of FIELDS) out += `            ${field}: f(Role::${role}, self.${field}),\n`;
    out += '        }\n    }\n}\n\n';
    out += '/// One theme as the package ships it.\n#[derive(Clone, Copy, Debug)]\npub struct Theme {\n';
    out += "    pub name: &'static str,\n    pub dark: bool,\n    /// `--fx-duration`, in milliseconds.\n    pub fx_duration_ms: u32,\n";
    out += '    pub palette: Palette<Rgb>,\n}\n\n';
    out += "/// Every theme, in the package's own order (`themes/order.json`).\n";
    out += `pub const THEMES: [Theme; ${all.length}] = [\n`;
    for (const theme of all) {
        const values = { ...theme.tokens, ...derivedBlock(theme.name) };
        const dark = values['color-scheme'] === 'dark';
        const ms = Number.parseInt(String(values['fx-duration'] ?? '180ms'), 10) || 180;
        out += `    Theme {\n        name: ${JSON.stringify(theme.name)},\n        dark: ${dark},\n        fx_duration_ms: ${ms},\n        palette: Palette {\n`;
        for (const [field, token] of FIELDS) {
            const value = values[token];
            if (value === undefined) throw new Error(`${theme.name}: --${token} is missing`);
            const [r, g, b] = rgbOf(value);
            out += `            ${field}: Rgb(${r}, ${g}, ${b}), // ${value}\n`;
        }
        out += '        },\n    },\n';
    }
    out += '];\n';
    return out;
}

function main() {
    const text = render();
    const path = new URL('generated_palette.rs', OUT);
    if (process.argv.includes('--check')) {
        let current = '';
        try {
            current = readFileSync(path, 'utf8');
        } catch {
            current = '';
        }
        if (current !== text) {
            console.error('crates/kp-tui-palette/src/generated_palette.rs does not match its source.');
            console.error('Run `node gates/generate-tui-palette.mjs` and commit the result.');
            process.exit(1);
        }
        const count = (text.match(/^    Theme \{$/gm) ?? []).length;
        console.log(`TUI palette: ${count} themes and ${FIELDS.length} colours each match their source.`);
        process.exit(0);
    }
    mkdirSync(OUT, { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote crates/kp-tui-palette/src/generated_palette.rs from ${themes().length} themes.`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
